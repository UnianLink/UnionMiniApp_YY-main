/**
 * 📱 智能设备选择配置文件
 * 用于控制小程序端RSSI滤波和智能设备识别的所有参数
 * 开发者可通过修改这些参数来优化设备选择算法的表现
 */

const DeviceSelectionConfig = {
  // ===== RSSI 信号强度判断参数 =====
  
  /**
   * "明显更强"的RSSI阈值差值（dBm）
   * 当一个设备比其他设备强出此差值时，认为是明显领先
   * 调试建议：
   * - 设置过低(如3-5dBm)：容易在相近设备间频繁切换推荐
   * - 设置过高(如12-15dBm)：只有信号差距很大才会推荐，更保守
   * - 推荐值：8dBm，适合大部分环境
   */
  RSSI_STRONG_THRESHOLD: 8,

  /**
   * 极近距离RSSI阈值（贴手机背面）
   * 当RSSI高于此值时，认为设备极可能贴在手机背面
   * 调试建议：
   * - 设置过低(如-50dBm)：可能误判远距离强信号设备
   * - 设置过高(如-30dBm)：只有贴得很近才识别，可能漏检
   * - 推荐值：-40dBm，适合典型硬件功率
   */
  RSSI_PROXIMITY_THRESHOLD: -40,

  /**
   * 候选设备最小RSSI值
   * 低于此值的设备直接忽略，不参与智能选择
   * 调试建议：
   * - 设置过低(如-85dBm)：包含太多远距离噪声设备
   * - 设置过高(如-60dBm)：可能过滤掉一些有效设备
   * - 推荐值：-70dBm，过滤掉信号很弱的设备
   */
  RSSI_CANDIDATE_MIN: -70,

  // ===== RSSI 滤波和稳定性参数 =====

  /**
   * RSSI历史记录数量（用于移动平均滤波）
   * 越多的样本能提供更稳定的滤波结果，但响应会更慢
   * 调试建议：
   * - 设置过少(如3-4)：滤波效果差，容易受瞬时干扰
   * - 设置过多(如15-20)：响应太慢，用户等待时间长
   * - 推荐值：8，平衡稳定性和响应速度
   */
  RSSI_HISTORY_SIZE: 8,

  /**
   * RSSI标准差阈值（dBm）
   * 小于此值认为信号稳定，可以用于推荐
   * 调试建议：
   * - 设置过低(如1.5dBm)：要求过于苛刻，很难达到
   * - 设置过高(如6dBm)：即使信号很不稳定也会推荐
   * - 推荐值：3.0dBm，适合一般环境的信号稳定性
   */
  RSSI_STABILITY_THRESHOLD: 3.0,

  /**
   * 需要持续稳定的时间（毫秒）
   * 设备需要观察此时间才能建立足够的置信度
   * 调试建议：
   * - 设置过短(如2000ms)：可能基于不充分数据做决策
   * - 设置过长(如8000ms)：用户等待时间过长，体验差
   * - 推荐值：4000ms，给足够时间收集稳定数据
   */
  RSSI_STABLE_TIME: 4000,

  /**
   * 最小置信度阈值（0-1之间）
   * 只有置信度超过此值的设备才会被推荐
   * 调试建议：
   * - 设置过低(如0.6)：可能推荐不够稳定的设备
   * - 设置过高(如0.95)：要求过于严格，很少能推荐
   * - 推荐值：0.8，要求较高的置信度才推荐
   */
  RSSI_CONFIDENCE_MIN: 0.8,

  // ===== 推荐撤回控制参数 =====

  /**
   * 撤回推荐的置信度阈值
   * 当已推荐设备的置信度降到此值以下时，撤回推荐
   * 调试建议：
   * - 设置过低(如0.4)：很少撤回推荐，可能保持不稳定推荐
   * - 设置过高(如0.85)：频繁撤回推荐，用户体验不稳定
   * - 推荐值：0.6，低于推荐阈值但给一定缓冲
   */
  REVOCATION_CONFIDENCE_THRESHOLD: 0.6,

  // ===== 算法行为控制参数 =====

  /**
   * 最少样本数要求
   * 少于此样本数的设备不参与稳定性计算
   * 调试建议：
   * - 设置过少(如2)：基于很少数据就判断稳定性
   * - 设置过多(如8)：需要等待很久才开始判断
   * - 推荐值：4，确保有基本的统计意义
   */
  MIN_SAMPLES_FOR_STABILITY: 4,

  /**
   * 等待明显强信号设备出现的时间（毫秒）
   * 在此时间内，算法会等待是否有明显更强的设备出现
   * 调试建议：
   * - 设置过短(如1000ms)：可能错过后出现的更强设备
   * - 设置过长(如8000ms)：用户等待时间过长
   * - 推荐值：3000ms，给足够时间发现所有附近设备
   */
  DEVICE_SELECTION_WAIT_TIME: 3000,

  // ===== 置信度计算权重 =====

  /**
   * 时间因子权重（0-1之间）
   * 在置信度计算中，观察时间长度的权重
   */
  CONFIDENCE_WEIGHT_TIME: 0.4,

  /**
   * 稳定性因子权重（0-1之间）
   * 在置信度计算中，信号稳定性的权重
   */
  CONFIDENCE_WEIGHT_STABILITY: 0.4,

  /**
   * 样本数因子权重（0-1之间）
   * 在置信度计算中，历史样本数量的权重
   */
  CONFIDENCE_WEIGHT_SAMPLES: 0.2,

  // ===== 调试和日志控制 =====

  /**
   * 是否启用详细的设备选择日志
   * true: 输出详细的算法决策过程，便于调试
   * false: 只输出关键结果，减少日志噪声
   */
  ENABLE_SELECTION_DEBUG_LOG: true,

  /**
   * 是否在界面显示调试信息
   * true: 在设备列表中显示RSSI历史、稳定性等调试信息
   * false: 只显示基本的设备信息
   */
  ENABLE_UI_DEBUG_INFO: true,

  // ===== 性能优化参数 =====

  /**
   * 设备历史清理周期（毫秒）
   * 定期清理长时间未更新的设备历史数据
   */
  DEVICE_HISTORY_CLEANUP_INTERVAL: 30000,

  /**
   * 设备历史保留时间（毫秒）
   * 超过此时间未更新的设备历史将被清理
   */
  DEVICE_HISTORY_RETENTION_TIME: 60000
};

// 导出配置对象
module.exports = DeviceSelectionConfig;

/**
 * 🔧 调试指南
 * 
 * 1. 信号太敏感，频繁切换推荐：
 *    - 增加 RSSI_STRONG_THRESHOLD (如改为10-12)
 *    - 增加 RSSI_STABLE_TIME (如改为5000-6000)
 *    - 降低 RSSI_STABILITY_THRESHOLD (如改为2.0-2.5)
 * 
 * 2. 很难触发推荐，总是在等待：
 *    - 降低 RSSI_CONFIDENCE_MIN (如改为0.7-0.75)
 *    - 降低 RSSI_STABILITY_THRESHOLD (如改为4.0-5.0)
 *    - 减少 RSSI_STABLE_TIME (如改为3000)
 * 
 * 3. 推荐了错误的远距离设备：
 *    - 提高 RSSI_PROXIMITY_THRESHOLD (如改为-35)
 *    - 增加 RSSI_STRONG_THRESHOLD (如改为10)
 *    - 提高 RSSI_CANDIDATE_MIN (如改为-65)
 * 
 * 4. 贴近的设备识别不出来：
 *    - 降低 RSSI_PROXIMITY_THRESHOLD (如改为-45)
 *    - 降低 RSSI_CONFIDENCE_MIN (如改为0.7)
 *    - 减少 MIN_SAMPLES_FOR_STABILITY (如改为3)
 * 
 * 5. 算法响应太慢：
 *    - 减少 RSSI_HISTORY_SIZE (如改为6)
 *    - 减少 RSSI_STABLE_TIME (如改为3000)
 *    - 减少 MIN_SAMPLES_FOR_STABILITY (如改为3)
 * 
 * 修改这些参数后，重新启动小程序即可生效，无需重新编译ESP32固件。
 */